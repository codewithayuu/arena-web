export const ALL_DSA_PROBLEMS: DsaProblemCard[] = DSA_PROBLEM_SECTIONS.flatMap(
  (s) => s.problems,
);

export function getProblemBySlug(slug: string): DsaProblemCard | undefined {
  return ALL_DSA_PROBLEMS.find((p) => p.slug === slug);
}

export function getProblemSection(slug: string): DsaProblemSection | undefined {
  return DSA_PROBLEM_SECTIONS.find((s) =>
    s.problems.some((p) => p.slug === slug),
  );
}

export function getAllProblemCategories(): string[] {
  return DSA_PROBLEM_SECTIONS.map((s) => s.category);
}
