export function getAllLessons(): DsaLesson[] {
  return DSA_CURRICULUM.flatMap((m) => m.items);
}

export function getLessonBySlug(
  slug: string,
): { lesson: DsaLesson; moduleTitle: string } | null {
  for (const mod of DSA_CURRICULUM) {
    const lesson = mod.items.find((item) => item.slug === slug);
    if (lesson) {
      return { lesson, moduleTitle: mod.title };
    }
  }
  return null;
}

export function getAdjacentLessons(slug: string): {
  prev: DsaLesson | null;
  next: DsaLesson | null;
} {
  const all = getAllLessons();
  const idx = all.findIndex((l) => l.slug === slug);
  if (idx === -1) return { prev: null, next: null };
  return {
    prev: idx > 0 ? all[idx - 1] : null,
    next: idx < all.length - 1 ? all[idx + 1] : null,
  };
}
